"""Turns design/icons/*.svg into app/.../ui/icons/AppIcons.kt (Compose ImageVectors, built lazily)
and design/launcher/*.svg into Android vector drawables plus the adaptive launcher icon.

Run from the project root after editing any SVG:  python -I design/to_android.py
Supported SVG: path, circle, ellipse (with rotate), rect (with rx); fill="currentColor" or a stroke.
"""
import math
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, 'design', 'icons')
LAUNCHER = os.path.join(ROOT, 'design', 'launcher')
KT = os.path.join(ROOT, 'app', 'src', 'main', 'java', 'app', 'brano', 'ui', 'icons', 'AppIcons.kt')
RES = os.path.join(ROOT, 'app', 'src', 'main', 'res')
NS = '{http://www.w3.org/2000/svg}'
MIRRORED = {'Back'}


def n(v):
    return f'{v:.3f}'.rstrip('0').rstrip('.')


def circle_d(cx, cy, r):
    return f'M{n(cx - r)} {n(cy)}a{n(r)} {n(r)} 0 1 0 {n(2 * r)} 0a{n(r)} {n(r)} 0 1 0 {n(-2 * r)} 0z'


def ellipse_d(cx, cy, rx, ry, rot):
    a = math.radians(rot)
    dx, dy = rx * math.cos(a), rx * math.sin(a)
    x1, y1, x2, y2 = cx - dx, cy - dy, cx + dx, cy + dy
    return (f'M{n(x1)} {n(y1)}A{n(rx)} {n(ry)} {n(rot)} 1 0 {n(x2)} {n(y2)}'
            f'A{n(rx)} {n(ry)} {n(rot)} 1 0 {n(x1)} {n(y1)}z')


def rect_d(x, y, w, h, r):
    if r <= 0:
        return f'M{n(x)} {n(y)}h{n(w)}v{n(h)}h{n(-w)}z'
    return (f'M{n(x + r)} {n(y)}h{n(w - 2 * r)}a{n(r)} {n(r)} 0 0 1 {n(r)} {n(r)}v{n(h - 2 * r)}'
            f'a{n(r)} {n(r)} 0 0 1 {n(-r)} {n(r)}h{n(-(w - 2 * r))}a{n(r)} {n(r)} 0 0 1 {n(-r)} {n(-r)}'
            f'v{n(-(h - 2 * r))}a{n(r)} {n(r)} 0 0 1 {n(r)} {n(-r)}z')


def shapes(svg_path):
    """Yields dicts: d, fill (colour or None), stroke (colour or None), width, evenodd, opacity."""
    root = ET.parse(svg_path).getroot()
    for el in root.iter():
        tag = el.tag.replace(NS, '')
        a = el.attrib
        f = lambda k, d=0.0: float(a.get(k, d))
        if tag == 'path':
            d = a['d']
        elif tag == 'circle':
            d = circle_d(f('cx'), f('cy'), f('r'))
        elif tag == 'ellipse':
            rot = re.search(r'rotate\(\s*(-?[\d.]+)', a.get('transform', ''))
            d = ellipse_d(f('cx'), f('cy'), f('rx'), f('ry'), float(rot.group(1)) if rot else 0.0)
        elif tag == 'rect':
            d = rect_d(f('x'), f('y'), f('width'), f('height'), f('rx'))
        else:
            continue
        stroke = a.get('stroke')
        fill = a.get('fill', 'currentColor' if not stroke else 'none')
        yield {
            'd': ' '.join(d.split()),
            'fill': None if fill == 'none' else fill,
            'stroke': stroke if stroke and stroke != 'none' else None,
            'width': float(a.get('stroke-width', 1)),
            'evenodd': a.get('fill-rule') == 'evenodd',
            'stroke_opacity': float(a.get('stroke-opacity', 1)),
            'round': a.get('stroke-linecap') == 'round',
        }


def kotlin_icons():
    names = sorted(f[:-4] for f in os.listdir(ICONS) if f.endswith('.svg'))
    props = []
    for name in names:
        parts = []
        for s in shapes(os.path.join(ICONS, name + '.svg')):
            if s['stroke']:
                parts.append(f'line("{s["d"]}", {n(s["width"])}f)')
            else:
                parts.append(f'fill("{s["d"]}"' + (', evenOdd = true' if s['evenodd'] else '') + ')')
        if name in MIRRORED:
            parts.append('autoMirror = true')  # named argument: must follow the positional parts
        mirror = ''
        body = ',\n            '.join(parts)
        props.append(f'    val {name}: ImageVector by lazy {{\n        icon(\n            "{name}"{mirror},\n            {body},\n        )\n    }}')
    all_list = ', '.join(names)
    return f'''package app.brano.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// GENERATED by design/to_android.py from design/icons/*.svg: edit the SVGs, then run the script.

/**
 * The only place icons are referenced; screens use these names. Brano's own set (24x24, 2px round
 * strokes); each icon is built on first use, so unused ones cost nothing at startup.
 */
object AppIcons {{
{chr(10).join(props)}

    /** Every icon, for tests. */
    val all: List<ImageVector> get() = listOf({all_list})
}}

private class Part(val d: String, val stroke: Float, val evenOdd: Boolean)

private fun fill(d: String, evenOdd: Boolean = false) = Part(d, 0f, evenOdd)

private fun line(d: String, width: Float) = Part(d, width, false)

/** Black parts: Icon tints the whole vector with the content colour. */
private fun icon(name: String, vararg parts: Part, autoMirror: Boolean = false): ImageVector =
    ImageVector.Builder(
        name = "Brano.$name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
        autoMirror = autoMirror,
    ).apply {{
        for (p in parts) {{
            if (p.stroke > 0f) {{
                addPath(
                    addPathNodes(p.d),
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = p.stroke,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }} else {{
                addPath(
                    addPathNodes(p.d),
                    fill = SolidColor(Color.Black),
                    pathFillType = if (p.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                )
            }}
        }}
    }}.build()
'''


def argb(c, opacity=1.0):
    c = c.lstrip('#').upper()
    if len(c) == 3:
        c = ''.join(ch * 2 for ch in c)
    return f'#{round(opacity * 255):02X}{c}'


def vector_drawable(svg_name, size):
    out = []
    for s in shapes(os.path.join(LAUNCHER, svg_name)):
        attrs = [f'android:pathData="{s["d"]}"']
        if s['stroke']:
            attrs += [f'android:strokeColor="{argb(s["stroke"], s["stroke_opacity"])}"',
                      f'android:strokeWidth="{n(s["width"])}"']
            if s.get('round'):
                attrs.append('android:strokeLineCap="round"')
        elif s['fill'] and s['fill'].startswith('url('):
            attrs.append('android:fillColor="@android:color/transparent"')
        elif s['fill']:
            attrs.append(f'android:fillColor="{argb(s["fill"])}"')
        if s['evenodd']:
            attrs.append('android:fillType="evenOdd"')
        out.append('    <path ' + '\n        '.join(attrs) + ' />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by design/to_android.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n' + '\n'.join(out) + '\n</vector>\n')


BACKGROUND = '''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by design/to_android.py: radial gradient as in design/launcher/launcher_background.svg -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0 0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="54"
                android:gradientRadius="64" android:startColor="#FF2E2266" android:endColor="#FF14101F" />
        </aapt:attr>
    </path>
</vector>
'''

ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8', newline='\n').write(text)


def main():
    write(KT, kotlin_icons())
    drawable = os.path.join(RES, 'drawable')
    write(os.path.join(drawable, 'ic_launcher_background.xml'), BACKGROUND)
    write(os.path.join(drawable, 'ic_launcher_foreground.xml'), vector_drawable('launcher_foreground.svg', 108))
    write(os.path.join(drawable, 'ic_launcher_monochrome.xml'), vector_drawable('launcher_monochrome.svg', 108))
    # Same name as Media3's default small icon, so the playback notification uses Brano's.
    write(os.path.join(drawable, 'media3_notification_small_icon.xml'), vector_drawable('notification.svg', 24))
    for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        write(os.path.join(RES, 'mipmap-anydpi-v26', name), ADAPTIVE)
    print('ok')


if __name__ == '__main__':
    main()
